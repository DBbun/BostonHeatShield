"""Export the tract table and facility points to demo/data.js for the static map.

Usage: python src/export_demo_data.py [processed_dir] [raw_dir] [demo_dir]

Reads data_processed/boston_tracts.geojson (from build_tract_table.py) and the facility points in
data_raw. Writes a small JavaScript file that defines TRACTS and FACILITIES, so the demo opens
from a plain file or GitHub Pages with no server.

Climate Ready Boston shares are not exported: for 47 tracts they come from an overlapping 2010
tract, which is not the same area. The neighborhood name is exported with a flag for those tracts.
"""
import json
import sys
from pathlib import Path

import geopandas as gpd
import numpy as np

from gtfs_utils import load_rapid_lines, load_stops

ROOT = Path(__file__).resolve().parents[1]
PROC = Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / "data_processed"
RAW = Path(sys.argv[2]) if len(sys.argv) > 2 else ROOT / "data_raw"
DEMO = Path(sys.argv[3]) if len(sys.argv) > 3 else ROOT / "demo"

PROPS = {
    "GEOID": "id",
    "neighborhood": "hood",
    "svi_E_TOTPOP": "pop",
    "svi_RPL_THEMES": "svi",
    "svi_EP_POV150": "pov",
    "svi_EP_AGE65": "age65",
    "svi_EP_DISABL": "disab",
    "svi_EP_NOVEH": "noveh",
    "svi_EP_LIMENG": "limeng",
    "svi_MP_POV150": "pov_m",
    "svi_MP_AGE65": "age65_m",
    "svi_MP_DISABL": "disab_m",
    "svi_MP_NOVEH": "noveh_m",
    "svi_MP_LIMENG": "limeng_m",
    "lace_NO_AC_PE": "noac",
    "lace_NO_AC_PM": "noac_m",
    "lace_NO_AC_E": "noac_n",
    "lace_HSE_OCC_E": "occ",
    "places_casthma_pct": "asthma",
    "places_copd_pct": "copd",
    "places_diabetes_pct": "diabetes",
    "places_casthma_lo": "asthma_lo",
    "places_casthma_hi": "asthma_hi",
    "places_copd_lo": "copd_lo",
    "places_copd_hi": "copd_hi",
    "places_diabetes_lo": "diabetes_lo",
    "places_diabetes_hi": "diabetes_hi",
    "n_community_centers": "n_cc",
    "n_pools": "n_pool",
    "n_rapid_stations": "n_rapid",
    "n_commuter_rail_stations": "n_cr",
    "n_bus_stops": "n_bus",
}


def clean(v):
    if v is None or (isinstance(v, float) and np.isnan(v)):
        return None
    if isinstance(v, (np.integer,)):
        return int(v)
    if isinstance(v, (np.floating,)):
        return round(float(v), 3)
    return v


def round_coords(c, nd=5):
    if isinstance(c[0], (int, float)):
        return [round(c[0], nd), round(c[1], nd)]
    return [round_coords(x, nd) for x in c]


def main() -> None:
    t = gpd.read_file(PROC / "boston_tracts.geojson")
    simple = t.to_crs(26986).simplify(12, preserve_topology=True).to_crs(4326)
    features = []
    for (_, row), geom in zip(t.iterrows(), simple):
        props = {short: clean(row[col]) for col, short in PROPS.items()}
        props["hood_approx"] = bool(row["crb_join"] == "overlap")
        g = json.loads(gpd.GeoSeries([geom]).to_json())["features"][0]["geometry"]
        g["coordinates"] = round_coords(g["coordinates"])
        features.append({"type": "Feature", "properties": props, "geometry": g})

    facilities = []
    for kind, f in [("Community center", "02_community_centers.geojson"),
                    ("Pool", "02_community_center_pools.geojson")]:
        p = gpd.read_file(RAW / f).to_crs(4326)
        for _, r in p.iterrows():
            facilities.append({"kind": kind, "name": r["SITE"], "hood": r.get("NEIGH"),
                               "lat": round(r.geometry.y, 5), "lng": round(r.geometry.x, 5)})

    # MBTA rapid transit lines and stations near Boston (within 3 km of the study tracts)
    zip_path = RAW / "08_mbta_gtfs.zip"
    area = t.to_crs(26986).geometry.union_all().buffer(3000)
    near = gpd.GeoSeries([area], crs=26986).to_crs(4326).iloc[0]
    lines = load_rapid_lines(zip_path)
    lines["geometry"] = gpd.GeoSeries(lines.geometry, crs=4326).to_crs(26986).simplify(8).to_crs(4326)
    lines = lines.assign(geometry=lines.geometry.intersection(near))
    lines = lines[~lines.geometry.is_empty]
    tline = []
    for _, r in lines.iterrows():
        g = json.loads(gpd.GeoSeries([r.geometry]).to_json())["features"][0]["geometry"]
        g["coordinates"] = round_coords(g["coordinates"])
        tline.append({"type": "Feature", "properties": {"name": r["name"], "color": r["color"]}, "geometry": g})
    stops = load_stops(zip_path)
    stations = []
    for kind, label in [("rapid", "Subway / light rail station"), ("commuter", "Commuter rail station")]:
        g = stops[kind][stops[kind].geometry.within(near)]
        for _, r in g.iterrows():
            stations.append({"kind": label, "name": r["stop_name"], "town": r["municipality"],
                             "lat": round(r.geometry.y, 5), "lng": round(r.geometry.x, 5)})

    DEMO.mkdir(exist_ok=True)
    out = DEMO / "data.js"
    out.write_text(
        "// Generated by src/export_demo_data.py from public data. Do not edit by hand.\n"
        "const TRANSIT_LINES = " + json.dumps({"type": "FeatureCollection", "features": tline},
                                              separators=(",", ":")) + ";\n"
        "const STATIONS = " + json.dumps(stations, separators=(",", ":")) + ";\n"
        "const TRACTS = " + json.dumps({"type": "FeatureCollection", "features": features},
                                        separators=(",", ":")) + ";\n"
        "const FACILITIES = " + json.dumps(facilities, separators=(",", ":")) + ";\n",
        encoding="utf-8")
    print(f"Wrote {out} ({out.stat().st_size / 1024:.0f} KB): {len(features)} tracts, "
          f"{len(facilities)} facilities, {len(tline)} line segments, {len(stations)} stations")
    print("Neighborhoods:", sorted({f['properties']['hood'] for f in features if f['properties']['hood']}))


if __name__ == "__main__":
    main()
